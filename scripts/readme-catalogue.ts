import type { LinkProblemKind } from './readme-links.ts';

// The README's "What it finds" block, built from docs/categories (plan 040/01/02): the catalogue and the danger levels
// of docs/categories/README.md, the title, danger level and example line of each category file. Pure: no file system.

export type Danger = 'High' | 'Low' | 'Medium' | 'Safe';

export const DANGERS: readonly Danger[] = ['Safe', 'Low', 'Medium', 'High'];

export type CatalogueRow = { readonly category: string; readonly danger: string; readonly file: string };

export type Category = {
  readonly category: string;
  readonly danger: Danger;
  readonly example: string;
  readonly file: string;
  readonly title: string;
};

export type Levels = ReadonlyMap<Danger, string>;

export type Problem = {
  readonly kind: LinkProblemKind | ProblemKind;
  readonly message: string;
  readonly where: string;
};

export type ProblemKind =
  | 'bad-example'
  | 'danger-mismatch'
  | 'duplicate-row'
  | 'markers'
  | 'missing-file'
  | 'no-example'
  | 'no-levels'
  | 'no-title'
  | 'stale-block'
  | 'unlisted-file';

export const MAX_EXAMPLE_LENGTH = 80;

export const START_MARKER =
  '<!-- what-it-finds:start — generated by `npm run readme:generate` from docs/categories; do not edit by hand -->';

export const END_MARKER = '<!-- what-it-finds:end -->';

const CATEGORIES_FOLDER = 'docs/categories';
const DANGER_PREFIX = '**Danger level:**';
const EXAMPLE_PREFIX = '**Example:**';
const TITLE_PREFIX = '# ';

const isDanger = (word: string): word is Danger => (DANGERS as readonly string[]).includes(word);

// The cells of every row of the first table after the heading line, header and separator skipped.
const tableAfter = (text: string, heading: string): readonly (readonly string[])[] => {
  const lines = text.split('\n');
  const start = lines.findIndex((line) => line.trim() === heading);
  if (start === -1) {
    return [];
  }

  const rows: string[] = [];
  for (const line of lines.slice(start + 1)) {
    const trimmed = line.trim();
    if (trimmed.startsWith('|')) {
      rows.push(trimmed);
    } else if (rows.length > 0 || trimmed.startsWith('#')) {
      break;
    }
  }

  return rows.slice(2).map((row) =>
    row
      .split('|')
      .slice(1, -1)
      .map((cell) => cell.trim()),
  );
};

const linkTarget = (cell: string): string => {
  const target = /\]\(([^)]*)\)/u.exec(cell)?.[1] ?? '';

  return target.startsWith('./') ? target.slice(2) : target;
};

export const parseCatalogue = (catalogueReadme: string): readonly CatalogueRow[] =>
  tableAfter(catalogueReadme, '## Catalogue').map((cells) => ({
    category: (cells[0] ?? '').replaceAll('`', ''),
    danger: cells[1] ?? '',
    file: linkTarget(cells[3] ?? ''),
  }));

export const parseLevels = (
  catalogueReadme: string,
): { readonly levels: Levels; readonly problems: readonly Problem[] } => {
  const levels = new Map<Danger, string>();
  for (const cells of tableAfter(catalogueReadme, '## Danger levels')) {
    const level = (cells[0] ?? '').replaceAll('**', '');
    if (isDanger(level)) {
      levels.set(level, cells[1] ?? '');
    }
  }

  const problems = DANGERS.filter((danger) => !levels.has(danger)).map((danger): Problem => ({
    kind: 'no-levels',
    message: `the "Danger levels" table has no row for ${danger}`,
    where: `${CATEGORIES_FOLDER}/README.md`,
  }));

  return { levels, problems };
};

const lineAfter = (lines: readonly string[], prefix: string): string | undefined =>
  lines
    .find((line) => line.startsWith(prefix))
    ?.slice(prefix.length)
    .trim();

const readCategory = (
  row: CatalogueRow,
  text: string,
): { readonly category?: Category; readonly problems: readonly Problem[] } => {
  const where = `${CATEGORIES_FOLDER}/${row.file}`;
  const problem = (kind: ProblemKind, message: string): Problem => ({ kind, message, where });
  const problems: Problem[] = [];
  const lines = text.split('\n');

  const title = lineAfter(lines, TITLE_PREFIX);
  if (title === undefined || title === '') {
    problems.push(problem('no-title', 'the file has no `# ` title line'));
  }

  const danger = lineAfter(lines, DANGER_PREFIX)?.split(/\s/u)[0] ?? '';
  if (!isDanger(danger)) {
    problems.push(
      problem('danger-mismatch', `the file's danger level "${danger}" is not one of ${DANGERS.join(', ')}`),
    );
  } else if (danger !== row.danger) {
    problems.push(problem('danger-mismatch', `the file says ${danger}, the catalogue says ${row.danger}`));
  }

  const example = lineAfter(lines, EXAMPLE_PREFIX) ?? '';
  if (example === '') {
    problems.push(problem('no-example', `the file has no \`${EXAMPLE_PREFIX} <text>\` line`));
  } else if (example.length > MAX_EXAMPLE_LENGTH) {
    problems.push(problem('bad-example', `the example is over ${String(MAX_EXAMPLE_LENGTH)} characters`));
  } else if (example.includes('|')) {
    problems.push(problem('bad-example', 'the example holds a `|`'));
  }

  if (problems.length > 0 || title === undefined || !isDanger(danger)) {
    return { problems };
  }

  return { category: { category: row.category, danger, example, file: row.file, title }, problems };
};

export const readCategories = (
  rows: readonly CatalogueRow[],
  files: ReadonlyMap<string, string>,
): { readonly categories: readonly Category[]; readonly problems: readonly Problem[] } => {
  const categories: Category[] = [];
  const problems: Problem[] = [];
  const seenCategories = new Set<string>();
  const seenFiles = new Set<string>();

  for (const row of rows) {
    const where = `${CATEGORIES_FOLDER}/${row.file}`;
    const repeated = seenCategories.has(row.category)
      ? `category ${row.category}`
      : seenFiles.has(row.file)
        ? `file ${row.file}`
        : undefined;
    if (repeated !== undefined) {
      seenFiles.add(row.file);
      problems.push({ kind: 'duplicate-row', message: `the catalogue names ${repeated} twice`, where });
      continue;
    }
    seenCategories.add(row.category);
    seenFiles.add(row.file);

    const text = files.get(row.file);
    if (text === undefined) {
      problems.push({ kind: 'missing-file', message: `the catalogue row ${row.category} names a missing file`, where });
      continue;
    }

    const read = readCategory(row, text);
    problems.push(...read.problems);
    if (read.category !== undefined) {
      categories.push(read.category);
    }
  }

  for (const file of files.keys()) {
    if (!seenFiles.has(file)) {
      problems.push({
        kind: 'unlisted-file',
        message: 'no row of the catalogue names this file',
        where: `${CATEGORIES_FOLDER}/${file}`,
      });
    }
  }

  return { categories, problems };
};

export const buildBlock = (categories: readonly Category[], levels: Levels): string => {
  const sorted = categories.toSorted((a, b) => DANGERS.indexOf(a.danger) - DANGERS.indexOf(b.danger));

  return [
    `Fresher knows **${String(categories.length)} kinds** of files, each with a danger level:`,
    '',
    ...DANGERS.map((danger) => `- **${danger}** — ${levels.get(danger) ?? ''}`),
    '',
    '| What | Where, for example | Danger |',
    '| --- | --- | --- |',
    ...sorted.map(
      (category) =>
        `| [${category.title}](${CATEGORIES_FOLDER}/${category.file}) | ${category.example} | ${category.danger} |`,
    ),
  ].join('\n');
};

export const replaceBlock = (
  readme: string,
  block: string,
): { readonly problem: Problem } | { readonly text: string } => {
  const lines = readme.split('\n');
  const starts = lines.flatMap((line, index) => (line === START_MARKER ? [index] : []));
  const ends = lines.flatMap((line, index) => (line === END_MARKER ? [index] : []));
  const [start] = starts;
  const [end] = ends;

  if (starts.length !== 1 || ends.length !== 1 || start === undefined || end === undefined || end < start) {
    return {
      problem: {
        kind: 'markers',
        message: 'the README needs exactly one start marker line and one end marker line after it',
        where: 'README.md',
      },
    };
  }

  const before = lines.slice(0, start + 1).join('\n');
  const after = lines.slice(end).join('\n');

  return { text: `${before}\n\n${block}\n\n${after}` };
};
